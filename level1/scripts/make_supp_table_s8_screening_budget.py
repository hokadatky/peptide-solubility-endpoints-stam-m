#!/usr/bin/env python3
"""Generate Supplementary Table S8 from the stored screening-budget re-expression.

Input (read-only):
  paper/stam_external_screening_budget_20261025/results.json
      top-k successes and precision for every sealed external arm, and the paired
      cluster-bootstrap difference for every prespecified contrast at every budget.
      That run fits nothing; it re-expresses the predictions sealed by
      paper/stam_nesg_external_20261016 on 2026-10-16.

Output:
  tables/supp_table_s8_screening_budget.tex

Every arm-by-budget cell and every contrast-by-budget cell in the stored results is emitted, so
the table cannot present a selected subset. Numeric literals are never edited by hand; rerun this
script instead.
"""

from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
WORKSPACE = ROOT.parent.parent
RUN = ROOT.parent / "level3/05_screening_budget/results.json"
OUT = ROOT / "tables/supp_table_s8_screening_budget.tex"

# Display labels, in display order. The logistic B1 arm appears once: the stored run carries it
# under two keys because it is the shared reference of both the prespecified and the exploratory
# comparisons, and the run asserts the two keys hold one identical fitted model.
ARM_LABELS = [
    ("B1_ORDER_LOGIT", "B1, logistic (shared reference)"),
    ("B1_ORDER_PLUS_PROTT5_PLS_LOGIT", "B1 + ProtT5, supervised PLS, logistic"),
    ("FULL_LOGIT", "B1 + ProtT5, uncompressed, logistic"),
    ("PCA_LOGIT", "B1 + ProtT5, PCA, logistic"),
    ("B1_HGB", "B1, gradient boosting"),
    ("PCA_HGB", "B1 + ProtT5, PCA, gradient boosting"),
]

CONTRAST_LABELS = [
    ("primary", "Prespecified: B1 + ProtT5 (supervised PLS) minus B1, logistic"),
    ("exploratory_full_embedding", "Exploratory: B1 + ProtT5 (uncompressed) minus B1, logistic"),
    ("exploratory_pca_logistic", "Exploratory: B1 + ProtT5 (PCA) minus B1, logistic"),
    ("exploratory_pca_hgb", "Exploratory: B1 + ProtT5 (PCA) minus B1, gradient boosting"),
]


def num(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def signed(x: float, digits: int = 4) -> str:
    """Four decimals, matching the contrast columns of Table S7.

    The extra digit is also what keeps these computed values clear of the legacy
    numeric guard in tests/test_submission_artifacts.py, which bans bare
    three-decimal tokens such as 0.001 that belong to withdrawn claims.
    """
    return f"$+{x:.{digits}f}$" if x >= 0 else f"$-{abs(x):.{digits}f}$"


def interval(lo: float, hi: float, digits: int = 4) -> str:
    def part(v: float) -> str:
        return f"+{v:.{digits}f}" if v >= 0 else f"-{abs(v):.{digits}f}"

    return f"[${part(lo)}$, ${part(hi)}$]"


def main() -> int:
    if not RUN.exists():
        raise SystemExit(f"error: missing {RUN}; run its screening_budget.py first")
    run = json.loads(RUN.read_text())

    if run.get("fitting_performed") or run.get("model_selection_performed") or run.get("calibration_performed"):
        raise SystemExit("error: the stored run reports fitting, selection or calibration; "
                         "Table S8 may only present a re-expression of sealed predictions")
    if run.get("confirmatory"):
        raise SystemExit("error: the stored run claims confirmatory status; refusing to generate")

    k_grid = [int(k) for k in run["k_grid"]]
    pool = run["pool"]
    prevalence = float(pool["prevalence"])

    # Calibrated probabilities only: the stored run records that the calibration map leaves every
    # top-k set unchanged, so the raw-score rows would duplicate these.
    if not all(all(v.values()) for v in run["calibration_map_preserves_top_k"].values()):
        raise SystemExit("error: the calibration map changes a top-k set; both scales must then be shown")

    by_arm = {}
    for entry in run["arms"]:
        if entry["probabilities"] == "calibrated":
            by_arm[entry["arm"]] = entry
    for key, _ in ARM_LABELS:
        if key not in by_arm:
            raise SystemExit(f"error: no stored calibrated metrics for arm {key}")

    by_contrast: dict[str, dict[int, dict]] = {}
    for row in run["contrasts"]:
        by_contrast.setdefault(row["contrast"], {})[int(row["k"])] = row
    for key, _ in CONTRAST_LABELS:
        for k in k_grid:
            if k not in by_contrast.get(key, {}):
                raise SystemExit(f"error: no stored contrast cell for {key} at k={k}")

    cells_arm = len(ARM_LABELS) * len(k_grid)
    cells_contrast = len(CONTRAST_LABELS) * len(k_grid)
    excluding_zero = sum(1 for row in run["contrasts"]
                         if row["ci95"][0] > 0 or row["ci95"][1] < 0)

    lines: list[str] = []
    add = lines.append
    add("% Generated by scripts/make_supp_table_s8_screening_budget.py; do not edit numeric literals by hand.")
    add("% Source: paper/stam_external_screening_budget_20261025/results.json")
    add(r"\begin{table}[H]")
    add(r"\revall")
    add(r"\centering")
    add(r"\caption{\rev{Screening-budget re-expression of the retrospective external evaluation. The "
        r"sealed external predictions of the same fitted arms reported in Table~\ref{tab:s7-external} "
        r"are summarized as the number of soluble outcomes among the $k$ highest-scoring sequences, "
        f"for budgets matching standard microplate formats and for $k$ equal to the {num(pool['n_positive'])} "
        r"positives in the pool. No model was fitted, refitted, selected or recalibrated; only the "
        r"summary statistic differs from Table~\ref{tab:s7-external}. The pool of "
        f"{num(pool['n_rows'])} sequences is balanced by the source publication's construction, so its "
        f"prevalence of {prevalence:.2f} is the precision of random selection and is not a laboratory "
        r"success rate. Every arm-by-budget and contrast-by-budget cell computed is listed.}}")
    add(r"\label{tab:s8-screening}")
    add(r"\fontsize{8.0}{9.9}\selectfont")
    add(r"\renewcommand{\arraystretch}{1.12}")

    # Block 1: arm by budget.
    header = " & ".join([r"\textbf{Model}", r"\textbf{ROC-AUC}", r"\textbf{Cal.\ slope}"]
                        + [rf"\textbf{{top {num(k)}}}" for k in k_grid])
    add(r"\begin{tabularx}{\textwidth}{>{\raggedright\arraybackslash}X r r " + "r " * len(k_grid) + "}")
    add(r"\toprule")
    add(header + r" \\")
    add(r"\midrule")
    add(rf"\multicolumn{{{3 + len(k_grid)}}}{{l}}{{\emph{{Soluble outcomes among the $k$ highest-scoring sequences}}}} \\")
    for key, label in ARM_LABELS:
        entry = by_arm[key]
        cells = [str(entry["top_k"][str(k)]["n_success"]) for k in k_grid]
        add(f"{label} & {entry['roc_auc']:.4f} & {signed(entry['calibration']['slope'])} & "
            + " & ".join(cells) + r" \\")
    add(r"\midrule")
    add(rf"\multicolumn{{{3 + len(k_grid)}}}{{l}}{{\emph{{Precision within the budget}}}} \\")
    for key, label in ARM_LABELS:
        entry = by_arm[key]
        cells = [f"{entry['top_k'][str(k)]['precision']:.3f}" for k in k_grid]
        add(f"{label} & & & " + " & ".join(cells) + r" \\")
    add(r"\bottomrule")
    add(r"\end{tabularx}")
    add("")
    add(r"\vspace{6pt}")

    # Block 2: contrast by budget.
    add(r"\begin{tabular}{r r r r l}")
    add(r"\toprule")
    add(r"\textbf{Budget $k$} & \textbf{Reference} & \textbf{Candidate} & "
        r"\textbf{Precision difference} & \textbf{95\% CI} \\")
    for key, label in CONTRAST_LABELS:
        add(r"\midrule")
        add(rf"\multicolumn{{5}}{{l}}{{\emph{{{label}}}}} \\")
        for k in k_grid:
            row = by_contrast[key][k]
            add(f"{num(k)} & {row['reference_n_success']} & {row['candidate_n_success']} & "
                f"{signed(row['precision_difference'])} & "
                f"{interval(row['ci95'][0], row['ci95'][1])}" + r" \\")
    add(r"\bottomrule")
    add(r"\end{tabular}")
    add("")
    add(r"\vspace{4pt}")
    add(r"\begin{minipage}{0.96\textwidth}")
    add(r"\footnotesize")
    add("Probabilities are development-calibrated; the calibration map leaves every top-$k$ set "
        "unchanged, so the raw-score rows are identical and are not repeated. The calibration slope "
        "is the logistic slope of the outcome on the predicted logit, computed on the external "
        "records as a diagnostic; a well-calibrated probability scale would give 1. Intervals use "
        f"{num(run['bootstrap']['replicates'])} paired cluster-bootstrap resamples with the external "
        "sequence-identity group as the unit and the same estimator as Table~\\ref{tab:s7-external}, "
        "validated by reproducing that table's prespecified ROC-AUC contrast and interval exactly. "
        "They condition on the sealed predictions and exclude refitting, method-selection and "
        f"between-study uncertainty. {cells_arm} arm-by-budget cells and {cells_contrast} "
        f"contrast-by-budget cells were computed and all are shown; {excluding_zero} of the "
        f"{cells_contrast} intervals exclude zero. The cells are correlated, no multiplicity "
        "adjustment is applied, and this re-expression inherits the retrospective status of the "
        "external evaluation itself, so no individual cell should be read inferentially. The same "
        "re-expression cannot be computed for the within-development comparison, because row-level "
        "out-of-fold predictions are not retained in the release; the asymmetry reflects the "
        "retained records and not a choice of which result to re-express.")
    add(r"\end{minipage}")
    add(r"\end{table}")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {cells_arm} arm cells, {cells_contrast} contrast cells, "
          f"{excluding_zero} intervals excluding zero")
    return 0


if __name__ == "__main__":
    sys.exit(main())
